/** Icon metadata is cheap; only reading [vector] builds its path data. */
class CourseIconOption(
    val key: String,
    val label: String,
    val category: String,
    vector: () -> ImageVector,
) {
    val vector: ImageVector by lazy(vector)
}

/** Index only metadata so lookups never need to build a vector. */
internal class CourseIconCatalog(val all: List<CourseIconOption>) {
    private val byKey = all.associateBy { it.key }

    fun find(key: String?): CourseIconOption? = byKey[key]
}

